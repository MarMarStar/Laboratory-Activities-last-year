a = float(input("Enter first number: "))
b = float(input("Enter second number: "))
opp = input("Enter +,-,*,/ ")

if  opp == "+":
    sum = a+b
    print(sum)
    
elif opp == "-":
    diff = a-b
    print(diff)
    
elif opp == "*":
    prod = a*b
    print(prod)

elif opp == "/":
    quot = a/b
    print(quot)
